function dxEU = eu_J2_short_period(coeEU_x, opts)

%% ============================================================
% COE -> equinoctial
% =============================================================

a0      = coeEU_x(1);
h0      = coeEU_x(2);
l0      = coeEU_x(3);
inc0    = coeEU_x(4);
Omega0  = coeEU_x(5);
lambda0 = coeEU_x(6);

%% ============================================================
% Constants
% =============================================================
Re = opts.Re;
J2 = opts.J2;

%% ============================================================
% Parameters
% =============================================================
beta0 = sind(inc0);
% opts.J2 is the positive oblateness magnitude (C20 = -J2).
% Use the signed zonal coefficient in the EU expressions. With positive
% G20 the circular-orbit da term has the opposite sign to the J2 force.
G20 = -J2 * (Re / a0)^2;
lambda_p = 1 - 3/2 * G20 * (3 - 4 * beta0);
L = lambda0;

%% ============================================================
% Delta a
% =============================================================
da1 = -3*a0*G20/(2 * lambda_p) * ( ...
    (2 - 7/2 * beta0^2) * l0 * cosd(L) ...
    + (2 - 5/2 * beta0^2) * h0 * sind(L) ...
    + beta0^2 * cosd(2 * L) ...
    + 7/2 * beta0^2 * (l0 * cosd(3 * L) + h0 * sind(3 * L)) ...
    );

% J2^2 second order term
da2 = ...
    3 * a0 / 4 * G20^2 * beta0^2 * ( ...
    7 * (2 - 3 * beta0^2) * cosd(2 * L) ...
    + beta0^2 * cosd(4 * L) ...
    );

da = da1 + da2;

%% ============================================================
% Delta h
% =============================================================
dh = ...
    -3 / (2 * lambda_p) * G20 * ( ...
    (1 - 7/4 * beta0^2) * sind(L) ...
    + (1 - 3 * beta0^2) * l0 * sind(2 * L) ...
    + (-3/2 + 2 * beta0^2) * h0 * cosd(2 * L) ...
    + 7/12 * beta0^2 * sind(3 * L) ...
    + 17/8 * beta0^2 * (l0 * sind(4 * L) - h0 * cosd(4 * L)) ...
    );

%% ============================================================
% Delta l
% =============================================================
dl = ...
    -3 / (2 * lambda_p) * G20 * ( ...
    (1 - 5/4 * beta0^2) * cosd(L) ...
    + 1/2 * (3 - 5 * beta0^2) * l0 * cosd(2 * L) ...
    + (2 - 3/2 * beta0^2) * h0 * sind(2 * L) ...
    + 7/12 * beta0^2 * cosd(3 * L) ...
    + 17/8 * beta0^2 * (l0 * cosd(4 * L) + h0 * sind(4 * L)) ...
    );

%% ============================================================
% Delta i
% =============================================================
di = ...
    -3 / (4 * lambda_p) * G20 * beta0 * cosd(inc0) * ( ...
    -l0 * cosd(L) + h0 * sind(L) + cosd(2 * L) ...
    + 7/3 * (l0 * cosd(3 * L) + h0 * sind(3 * L)) ...
    );

%% ============================================================
% Delta Omega
% =============================================================
dOmega = ...
    3 / (2 * lambda_p) * G20 * cosd(inc0) * ( ...
    7/2 * l0 * sind(L) - 5/2 * h0 * cosd(L) - 1/2 * sind(2 * L) ...
    - 7/6 * l0 * sind(3 * L) + 7/6 * h0 * cosd(3 * L) ...
    );

%% ============================================================
% Delta lambda
% =============================================================
dlambda = ...
    -3 / (2 * lambda_p) * G20 * ( ...
    (10 - 119/8 * beta0^2) * l0 * sind(L) ...
    + (85/8 * beta0^2 - 9) * h0 * cosd(L) ...
    + (2 * beta0^2 - 1/2) * sind(2 * L) ...
    + (-7/6 + 119/24 * beta0^2) * (l0 * sind(3 * L) - h0 * cosd(3 * L)) ...
    - (3 - 21/4 * beta0^2) * l0 * sind(L) ...
    + (3 - 15/4 * beta0^2) * h0 * cosd(L) ...
    - 3/4 * beta0^2 * sind(2 * L) ...
    - 21/12 * beta0^2 * (l0 * sind(3 * L) - h0 * cosd(3 * L)) ...
    );

%% ============================================================
% Convert Delta equinoctial to COE difference
% =============================================================
% Paper:
%
% Delta = Osculating - Mean
%
% Mean = Osculating - Delta
%
% Angles in the formulas are radians; the EU vector stores degrees.

dxEU = [da; dh; dl; rad2deg(di); rad2deg(dOmega); rad2deg(dlambda)];

end
