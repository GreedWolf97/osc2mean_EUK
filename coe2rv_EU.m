function [r_eci, v_eci] = coe2rv_EU(coe, mu)
% =========================================================================
% COE2RV_EU
%
% Classical orbital elements -> ECI position and velocity
%
% Input:
%   coe = [a e i RAAN omega M]
%
% Units:
%   a   : km
%   i   : deg
%   RAAN: deg
%   omega: deg
%   M   : deg
%
% Output:
%   r_eci : km
%   v_eci : km/s
%
% =========================================================================

a     = coe(1);
e     = coe(2);
inc   = coe(3);
Omega = coe(4);
omega = coe(5);
M     = coe(6);


%% ========================================================================
% 1. Solve Kepler equation
% =========================================================================

Mrad = deg2rad(M);

if e < 0.8
    E = Mrad;
else
    E = pi;
end

for k = 1:100

    f = E - e*sin(E) - Mrad;
    fp = 1 - e*cos(E);

    dE = -f/fp;

    E = E + dE;

    if abs(dE) < 1e-14
        break;
    end

end


%% ========================================================================
% 2. Eccentric anomaly -> true anomaly
% =========================================================================

nu = 2 * atan2( ...
    sqrt(1 + e) * sin(E/2), ...
    sqrt(1 - e) * cos(E/2));


%% ========================================================================
% 3. Radius
% =========================================================================

p = a * (1 - e^2);

rmag = p / (1 + e*cos(nu));


%% ========================================================================
% 4. Perifocal position
% =========================================================================

r_pf = [
    rmag*cos(nu)
    rmag*sin(nu)
    0
];


%% ========================================================================
% 5. Perifocal velocity
% =========================================================================

v_pf = sqrt(mu/p) * [
    -sin(nu)
     e + cos(nu)
     0
];


%% ========================================================================
% 6. Rotation matrix PQW -> ECI
% =========================================================================

i = deg2rad(inc);
O = deg2rad(Omega);
w = deg2rad(omega);

cO = cos(O);
sO = sin(O);

ci = cos(i);
si = sin(i);

cw = cos(w);
sw = sin(w);


R = [
     cO*cw - sO*sw*ci,   -cO*sw - sO*cw*ci,    sO*si
     sO*cw + cO*sw*ci,   -sO*sw + cO*cw*ci,   -cO*si
     sw*si,                cw*si,               ci
];


%% ========================================================================
% 7. ECI state
% =========================================================================

r_eci = R * r_pf;
v_eci = R * v_pf;

end