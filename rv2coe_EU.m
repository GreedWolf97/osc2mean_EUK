function coe = rv2coe_EU(r, v, mu)
% =========================================================================
% RV2COE_EU
%
% ECI position/velocity -> classical orbital elements
%
% Output:
%   coe = [a e i RAAN omega M]
%
% Units:
%   a   : km
%   i   : deg
%   RAAN: deg
%   omega: deg
%   M   : deg
%
% =========================================================================

r = r(:);
v = v(:);


%% ========================================================================
% 1. Magnitudes
% =========================================================================

R = norm(r);
V = norm(v);


%% ========================================================================
% 2. Angular momentum
% =========================================================================

h_vec = cross(r, v);
h = norm(h_vec);


%% ========================================================================
% 3. Inclination
% =========================================================================

inc = acos( ...
    max(-1, min(1, h_vec(3)/h)));


%% ========================================================================
% 4. Node vector
% =========================================================================

k = [0; 0; 1];

n_vec = cross(k, h_vec);
n = norm(n_vec);


%% ========================================================================
% 5. Eccentricity vector
% =========================================================================

e_vec = cross(v, h_vec)/mu - r/R;
e = norm(e_vec);


%% ========================================================================
% 6. Semi-major axis
% =========================================================================

energy = V^2/2 - mu/R;

a = -mu/(2*energy);


%% ========================================================================
% 7. RAAN
% =========================================================================

if n > 1e-14

    RAAN = atan2(n_vec(2), n_vec(1));

    if RAAN < 0
        RAAN = RAAN + 2*pi;
    end

else

    RAAN = 0;

end


%% ========================================================================
% 8. Argument of perigee
% =========================================================================

if e > 1e-14 && n > 1e-14

    omega = acos( ...
        max(-1, min(1, ...
        dot(n_vec, e_vec)/(n*e))));

    if e_vec(3) < 0
        omega = 2*pi - omega;
    end

else

    omega = 0;

end


%% ========================================================================
% 9. True anomaly
% =========================================================================

if e > 1e-14

    nu = acos( ...
        max(-1, min(1, ...
        dot(e_vec, r)/(e*R))));

    if dot(r,v) < 0
        nu = 2*pi - nu;
    end

else

    % Circular orbit.
    % For the present LEO test case e is nonzero, so this branch
    % is not normally used.

    if n > 1e-14

        nu = acos( ...
            max(-1, min(1, ...
            dot(n_vec,r)/(n*R))));

        if r(3) < 0
            nu = 2*pi - nu;
        end

    else

        nu = atan2(r(2),r(1));

        if nu < 0
            nu = nu + 2*pi;
        end

    end

end


%% ========================================================================
% 10. True anomaly -> eccentric anomaly
% =========================================================================

if e < 1

    E = 2 * atan2( ...
        sqrt(1-e)*sin(nu/2), ...
        sqrt(1+e)*cos(nu/2));

    % Force a positive [0,2pi) representation
    E = mod(E, 2*pi);

    M = E - e*sin(E);

else

    error('This function currently assumes an elliptic orbit (e < 1).');

end


%% ========================================================================
% 11. Convert angles to degrees
% =========================================================================

inc   = rad2deg(inc);
RAAN  = mod(rad2deg(RAAN),360);
omega = mod(rad2deg(omega),360);
M     = mod(rad2deg(M),360);


%% ========================================================================
% 12. Output
% =========================================================================

coe = [
    a
    e
    inc
    RAAN
    omega
    M
];

end